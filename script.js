const languageButtons = [...document.querySelectorAll("[data-language]")];
const metaDescription = document.querySelector('meta[name="description"]');
const languageStorageKey = "bernardo-portfolio-language";
let currentLanguage = "es";

const getStoredLanguage = () => {
  try {
    const storedLanguage = localStorage.getItem(languageStorageKey);
    return storedLanguage === "en" || storedLanguage === "es" ? storedLanguage : "es";
  } catch {
    return "es";
  }
};

const updateMenuLabel = (isOpen) => {
  const label = document.querySelector(".menu-toggle .sr-only");
  if (!label) return;

  label.textContent = translations[currentLanguage][
    isOpen ? "nav.closeMenu" : "nav.openMenu"
  ];
};

const setLanguage = (language, { persist = true } = {}) => {
  const copy = translations[language];
  if (!copy) return;

  currentLanguage = language;
  document.documentElement.lang = language;
  document.title = copy.metaTitle;
  metaDescription?.setAttribute("content", copy.metaDescription);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (typeof value === "string") element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-lines]").forEach((element) => {
    const values = copy[element.dataset.i18nLines];
    if (!Array.isArray(values)) return;

    const textNodes = [...element.childNodes].filter(
      (node) => node.nodeType === 3 && node.textContent.trim(),
    );
    values.forEach((value, index) => {
      if (textNodes[index]) textNodes[index].nodeValue = value;
    });
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const value = copy[element.dataset.i18nAria];
    if (typeof value === "string") element.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = copy[element.dataset.i18nAlt];
    if (typeof value === "string") element.setAttribute("alt", value);
  });

  languageButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.language === language));
  });
  updateMenuLabel(document.querySelector(".menu-toggle")?.getAttribute("aria-expanded") === "true");

  if (persist) {
    try {
      localStorage.setItem(languageStorageKey, language);
    } catch {
      // The language still changes when storage is unavailable.
    }
  }

  requestAnimationFrame(() => window.ScrollTrigger?.refresh());
};

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

setLanguage(getStoredLanguage(), { persist: false });

const menuButton = document.querySelector(".menu-toggle");
const navigation = document.querySelector(".nav");

menuButton?.addEventListener("click", () => {
  const isOpen = menuButton.getAttribute("aria-expanded") === "true";
  menuButton.setAttribute("aria-expanded", String(!isOpen));
  navigation?.classList.toggle("is-open", !isOpen);
  updateMenuLabel(!isOpen);
});

navigation?.addEventListener("click", (event) => {
  if (event.target instanceof HTMLAnchorElement) {
    menuButton?.setAttribute("aria-expanded", "false");
    navigation.classList.remove("is-open");
    updateMenuLabel(false);
  }
});

